// The member floor of the D8 candidate tier, from the existing Python labels by rule family (pre-registration,
// before any D8 labelling). For each candidate floor N it writes a derived view of each v3 dev part (py, py2) whose
// default tier is "Python call wrappers and layering, in-repo targets, role >= N members" (no guard condition: the
// labelled cards' guard facts were never recorded), scores it with metrics.mjs, and prints metrics.mjs's
// per-language, tier and rule family rows for Python. polar and CTFd are dropped from the views [STRICT]: the
// brief forbids scanning them, so no D8 card can come from them, and their labels should not set the floor.
// Labels are read as they are (eval/study/runs/dev-v3-2026-11-06/<part>/final.jsonl); nothing is relabelled.
//
//   node eval/study/runs/d8-prereg-2026-11-07/floors.mjs --out <scratch dir> > eval/study/runs/d8-prereg-2026-11-07/floors.md
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checkTier, familyOf, parseArgs, proposalLanguage, readJson } from "../../lib.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..", "..", "..");
const src = join(root, "eval", "study", "runs", "dev-v3-2026-11-06");
const args = parseArgs(process.argv.slice(2));
if (!args.out) throw new Error("usage: floors.mjs --out DIR");
const FLOORS = [15, 20, 30, 40, 50];
const DROP = new Set(["polar", "CTFd"]);
const tierAt = (n) => ({
  kind: "rule_kind",
  decision: `floor-${n}`,
  default: { rule_kinds: ["wrapped_by:call", "avoids:import"], languages: ["py"], min_members: n, target: "in_repo" },
  suggestion: { rule_kinds: [], languages: ["ts"] },
});

const out = [];
out.push("# D8 member floor: Python labels by rule family (metrics.mjs, #68)", "");
out.push("Generated by `floors.mjs`. Views of `runs/dev-v3-2026-11-06/{py,py2}` (rubric v3 labels, cards as labelled at `debc33a`; member counts and Python members as `views/d7` reads them), without polar and CTFd. Default tier of each view: Python `wrapped_by:call` or `avoids:import`, in-repo targets, role ≥ N members. Rates over all shown, unlabelled counted as WRONG. Dev, in-sample figures.", "");

// The member counts of every labelled Python card, by family (what a floor can be read from at all).
const items = [];
for (const part of ["py", "py2"]) {
  const q = readJson(join(src, part, "views", "d7", "queue.json"));
  const lab = new Map(readFileSync(join(src, part, "final.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l)).map((r) => [r.uid, r.label]));
  for (const p of q.items) if (!DROP.has(p.repo) && proposalLanguage(p) === "py") items.push({ part, ...p, family: familyOf(p), label: lab.get(p.uid) ?? "unlabelled" });
}
const fams = [...new Set(items.map((p) => p.family))];
out.push("## Role sizes of the labelled Python cards, by family", "");
out.push("| Family | Cards | Smallest role | ACCEPT / cards with role < 40 | ACCEPT / cards with role ≥ 40 |", "| --- | --- | --- | --- | --- |");
for (const f of fams.sort()) {
  const s = items.filter((p) => p.family === f);
  const a = (x) => `${x.filter((p) => p.label === "ACCEPT").length}/${x.length}`;
  out.push(`| ${f} | ${s.length} | ${Math.min(...s.map((p) => p.members))} | ${a(s.filter((p) => p.members < 40))} | ${a(s.filter((p) => p.members >= 40))} |`);
}
out.push(`| all Python | ${items.length} | ${Math.min(...items.map((p) => p.members))} | ${items.filter((p) => p.members < 40 && p.label === "ACCEPT").length}/${items.filter((p) => p.members < 40).length} | ${items.filter((p) => p.members >= 40 && p.label === "ACCEPT").length}/${items.filter((p) => p.members >= 40).length} |`, "");
out.push("Call-wrapper and layering cards (the D8 kinds), one per line:", "");
for (const p of items.filter((p) => ["wrapper", "layering"].includes(p.family)).sort((a, b) => a.members - b.members))
  out.push(`- ${p.uid} (${p.part}): ${p.members} members, ${p.label}; ${JSON.stringify(p.rule.any_of ?? p.rule.signal)}`);
out.push("");

const table = [];
for (const n of FLOORS) {
  const tier = tierAt(n);
  if (checkTier(tier).length) throw new Error(checkTier(tier).join("; "));
  for (const part of ["py", "py2"]) {
    const run = readJson(join(src, part, "run.json"));
    const q = readJson(join(src, part, "views", "d7", "queue.json"));
    const dir = join(resolve(args.out), `floor-${n}`, part);
    mkdirSync(dir, { recursive: true });
    const view = { ...run, run: dir, repos: run.repos.filter((r) => !DROP.has(r.name)), params: { ...run.params, tier, tier_pre_registered: false } };
    writeFileSync(join(dir, "run.json"), JSON.stringify(view, null, 2) + "\n");
    writeFileSync(join(dir, "queue.json"), JSON.stringify({ run: dir, items: q.items.filter((p) => !DROP.has(p.repo)) }, null, 2) + "\n");
    const md = execFileSync("node", [join(root, "eval", "study", "metrics.mjs"), "--run", dir, "--labels", join(src, part, "final.jsonl")], { encoding: "utf8" });
    const lines = md.split("\n");
    const at = lines.findIndex((l) => l.startsWith("## Per language, tier and rule family"));
    const end = lines.findIndex((l, i) => i > at && l.startsWith("## "));
    // Only the D8 kinds' families: every other Python family is suggestion tier at every floor.
    const rows = lines.slice(at, end).filter((l) => /^\| python \| (Call wrappers|Layering \(imports avoided\)) \|/.test(l));
    table.push(...rows.map((l) => l.replace(/^\| python \|/, `| ${n} | ${part} |`)));
  }
}
out.push("## The D8 kinds' families at each floor (metrics.mjs per-language, tier and rule family rows, Python)", "");
out.push("| Floor | Part | Family | Tier | Shown | ACCEPT | TRIVIAL | WRONG | Accept | Not-wrong |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |", ...table, "");
out.push("`py` has no Python call-wrapper or layering card at any floor. Every other Python family is suggestion tier in every view (not a D8 kind), so its rows do not depend on the floor; `metrics.mjs --run <out>/floor-N/<part>` prints them.", "");
console.log(out.join("\n"));
