#!/usr/bin/env node
// The round-10 fold assignment of the build set (eval/study/PLAN-R10.md §3.2): the 34 dev repos in 4 fixed
// folds, by a seeded shuffle stratified by language, recorded once in eval/study/folds-r10.json.
//
//   node eval/study/folds.mjs --check            (exit 1 unless the committed file is what its seed gives)
//   node eval/study/folds.mjs --print            (the assignment the seed gives, as JSON; writes nothing)
//
// The build set is read from the dev manifests only: eval/repos.json (TS/JS), eval/repos-py.json and
// eval/repos-py-2.json (Python), never polar or CTFd. Method, per language: the repo names in code-point order,
// shuffled with lib.mjs `shuffle` seeded by `<seed>:<language>` (mulberry32, Fisher-Yates), then dealt to folds
// 1..4 in turn, the i-th shuffled repo to fold (i mod 4) + 1. The file's `sha256` is over the canonical JSON of
// { seed, method, languages, folds }; `loadFolds` refuses a file whose hash or assignment does not match, so a
// hand edit cannot pass silently. The seed is fixed once and never re-rolled [STRICT].
//
// Round 11 (eval/study/PLAN-R11.md §5): eval/study/folds-r11.json is folds 1-4 of folds-r10.json exactly, plus fold 5 =
// dev3, the blind dev pool that joined the build set after its report (#132). Fold 5 is not shuffled: it is every repo
// of the two dev3 census manifests (eval/study/runs/dev3-{ts,py}-2026-11-08/manifest.json), by the opaque key the dev3
// runs name it by (T01.., P01..), in code-point order. The record keeps folds-r10.json's seed and sha256, and the
// sha256 of each dev3 census manifest; its own `sha256` is over the canonical JSON of { seed, method, base, fold5,
// languages, folds }. `foldsProblemsR11` refuses it unless folds-r10.json passes its own checks and its hash is the
// recorded one, folds 1-4 equal folds-r10.json's, each dev3 census manifest has the recorded hash and lists exactly the
// current slot occupants (url and pinned sha, lib.mjs effectiveRepos) of the frozen pool it names, with that pool's
// recorded sha256 and core, and the file is exactly what those inputs give.
//
//   node eval/study/folds.mjs --check            (checks folds-r10.json and folds-r11.json)
//   node eval/study/folds.mjs --print --r11      (the round-11 record the inputs give, as JSON; writes nothing)
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { coreSha, die, effectiveRepos, parseArgs, repoRootDir, sha256File, sha256Text, shuffle } from "./lib.mjs";

export const FOLDS_FILE = "eval/study/folds-r10.json";
export const SEED = "drift-r10-folds-2026-11-08";
export const N_FOLDS = 4;
export const EXCLUDED = ["polar", "CTFd"];
export const MANIFESTS = { ts: ["eval/repos.json"], py: ["eval/repos-py.json", "eval/repos-py-2.json"] };
export const METHOD =
  "per language (ts, py): repo names from the dev manifests (polar and CTFd excluded) in code-point order; lib.mjs shuffle(names, `${seed}:${language}`) (mulberry32 Fisher-Yates); the i-th shuffled repo goes to fold (i mod 4) + 1";

const byCodePoint = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// The build set per language, from the dev manifests.
export function buildSet(root = repoRootDir) {
  const out = {};
  for (const [lang, files] of Object.entries(MANIFESTS)) {
    const names = files.flatMap((f) => JSON.parse(readFileSync(join(root, f), "utf8")).repos.map((r) => r.name));
    if (new Set(names).size !== names.length) die(`duplicate repo name in ${files.join(", ")}`);
    out[lang] = names.filter((n) => !EXCLUDED.includes(n)).sort(byCodePoint);
  }
  return out;
}

// The assignment a seed gives for a build set: { seed, method, languages, folds: [{ fold, ts: [...], py: [...] }] }.
export function assignFolds(set, seed = SEED, n = N_FOLDS) {
  const folds = Array.from({ length: n }, (_, i) => ({ fold: i + 1, ...Object.fromEntries(Object.keys(set).map((l) => [l, []])) }));
  for (const [lang, names] of Object.entries(set)) shuffle([...names].sort(byCodePoint), `${seed}:${lang}`).forEach((name, i) => folds[i % n][lang].push(name));
  for (const f of folds) for (const lang of Object.keys(set)) f[lang].sort(byCodePoint);
  return { seed, method: METHOD, languages: Object.fromEntries(Object.entries(set).map(([l, v]) => [l, v.length])), folds };
}

export const foldsSha256 = (a) => sha256Text(JSON.stringify({ seed: a.seed, method: a.method, languages: a.languages, folds: a.folds }));

// The file as it is committed: the assignment, its hash and how to check it.
export function foldsRecord(set = buildSet(), seed = SEED) {
  const a = assignFolds(set, seed);
  return {
    "//": "Round-10 folds of the build set (eval/study/PLAN-R10.md §3.2). Generated by eval/study/folds.mjs and checked by folds.test.mjs: do not edit by hand.",
    plan: "eval/study/PLAN-R10.md §3.2",
    manifests: MANIFESTS,
    excluded: EXCLUDED,
    ...a,
    check: "node eval/study/folds.mjs --check",
    sha256: foldsSha256(a),
  };
}

// The problems with a folds record against the build set: an empty list when it is exactly what its seed gives.
export function foldsProblems(rec, set = buildSet()) {
  const p = [];
  if (!rec || typeof rec !== "object") return ["not an object"];
  if (rec.sha256 !== foldsSha256(rec)) p.push(`sha256 ${rec.sha256} does not match the assignment (${foldsSha256(rec)}): the file was edited`);
  const want = foldsRecord(set, rec.seed);
  if (JSON.stringify(rec) !== JSON.stringify(want)) p.push(`the file is not what seed ${JSON.stringify(rec.seed)} gives for the build set (regenerate nothing: the seed is fixed once)`);
  if (rec.seed !== SEED) p.push(`seed ${JSON.stringify(rec.seed)} is not the recorded seed ${JSON.stringify(SEED)}`);
  return p;
}

// ---------- round 11: folds 1-4 of round 10, plus fold 5 = dev3 ----------

export const FOLDS_FILE_R11 = "eval/study/folds-r11.json";
export const FOLD5 = 5;
export const DEV3_RUNS = { ts: "eval/study/runs/dev3-ts-2026-11-08", py: "eval/study/runs/dev3-py-2026-11-08" };
export const METHOD_R11 =
  "folds 1-4: eval/study/folds-r10.json exactly (its seed and method; its sha256 recorded and checked); fold 5: every repo of the dev3 census manifests (eval/study/runs/dev3-{ts,py}-2026-11-08/manifest.json: the current slot occupants of the frozen pools eval/dev3-2026-11-08.json and eval/dev3-2026-11-08-py.json after their replaced swaps), by its opaque key, in code-point order; no shuffle";

// Fold 5 from the dev3 census manifests: { set: { ts: [keys], py: [keys] }, sources: { lang: {...hashes} }, problems }.
export function fold5Inputs(root = repoRootDir) {
  const set = {};
  const sources = {};
  const problems = [];
  for (const [lang, run] of Object.entries(DEV3_RUNS)) {
    const file = `${run}/manifest.json`;
    const m = JSON.parse(readFileSync(join(root, file), "utf8"));
    const runRec = JSON.parse(readFileSync(join(root, run, "run.json"), "utf8"));
    const src = JSON.parse(readFileSync(join(root, m.source.manifest), "utf8"));
    const sha = sha256File(join(root, file));
    if (runRec.manifest?.sha256 !== sha) problems.push(`${file}: sha256 ${sha} is not the one its census ran from (${run}/run.json ${runRec.manifest?.sha256})`);
    if (sha256File(join(root, m.source.manifest)) !== m.source.sha256) problems.push(`${m.source.manifest}: sha256 is not the one ${file} records`);
    if (coreSha(src) !== m.source.core_sha256) problems.push(`${m.source.manifest}: core sha256 is not the one ${file} records`);
    const pins = (rs) => JSON.stringify(rs.map((r) => `${r.url}@${r.sha}`));
    if (pins(m.repos) !== pins(effectiveRepos(src))) problems.push(`${file}: its repos are not the current slot occupants of ${m.source.manifest} (url@sha, in slot order)`);
    const keys = m.repos.map((r) => r.name);
    if (new Set(keys).size !== keys.length) problems.push(`${file}: duplicate key`);
    set[lang] = [...keys].sort(byCodePoint);
    sources[lang] = { census_manifest: file, sha256: sha, frozen_manifest: m.source.manifest, frozen_sha256: m.source.sha256, frozen_core_sha256: m.source.core_sha256, set_id: m.set_id };
  }
  return { set, sources, problems };
}

export const foldsSha256R11 = (a) => sha256Text(JSON.stringify({ seed: a.seed, method: a.method, base: a.base, fold5: a.fold5, languages: a.languages, folds: a.folds }));

// The round-11 record the inputs give (folds-r10.json as committed, and the dev3 census manifests).
export function foldsRecordR11(root = repoRootDir) {
  const r10 = JSON.parse(readFileSync(join(root, FOLDS_FILE), "utf8"));
  const f5 = fold5Inputs(root);
  const folds = [...r10.folds.map((f) => ({ ...f })), { fold: FOLD5, ts: f5.set.ts, py: f5.set.py }];
  const languages = Object.fromEntries(Object.keys(r10.languages).map((l) => [l, r10.languages[l] + f5.set[l].length]));
  const a = { seed: r10.seed, method: METHOD_R11, base: { file: FOLDS_FILE, sha256: r10.sha256 }, fold5: f5.sources, languages, folds };
  return {
    "//": "Round-11 folds of the build set (eval/study/PLAN-R11.md §5): folds 1-4 of folds-r10.json, plus fold 5 = dev3 by key. Generated by eval/study/folds.mjs and checked by folds.test.mjs: do not edit by hand.",
    plan: "eval/study/PLAN-R11.md §5",
    manifests: r10.manifests,
    excluded: r10.excluded,
    ...a,
    check: "node eval/study/folds.mjs --check",
    sha256: foldsSha256R11(a),
  };
}

// The problems with a round-11 record: an empty list when it is exactly what its inputs give. Each check is one line,
// so a mutation of it is a one-line edit (folds.test.mjs mutates each and expects a check to fail).
export function foldsProblemsR11(rec, root = repoRootDir) {
  const p = [];
  if (!rec || typeof rec !== "object") return ["not an object"];
  const r10 = JSON.parse(readFileSync(join(root, FOLDS_FILE), "utf8"));
  const r10p = foldsProblems(r10, buildSet(root));
  if (r10p.length) p.push(`${FOLDS_FILE} fails its own checks: ${r10p.join("; ")}`); // mutation:r10
  if (rec.sha256 !== foldsSha256R11(rec)) p.push(`sha256 ${rec.sha256} does not match the assignment (${foldsSha256R11(rec)}): the file was edited`); // mutation:hash
  if (rec.base?.sha256 !== r10.sha256) p.push(`base sha256 ${rec.base?.sha256} is not ${FOLDS_FILE}'s (${r10.sha256})`); // mutation:base
  if (JSON.stringify(rec.folds?.slice(0, N_FOLDS)) !== JSON.stringify(r10.folds)) p.push(`folds 1-${N_FOLDS} are not ${FOLDS_FILE}'s`); // mutation:folds14
  const f5 = fold5Inputs(root);
  p.push(...f5.problems); // mutation:fold5src
  const five = rec.folds?.[N_FOLDS];
  if (!five || five.fold !== FOLD5 || JSON.stringify([five.ts, five.py]) !== JSON.stringify([f5.set.ts, f5.set.py])) p.push(`fold ${FOLD5} is not the dev3 census manifests' keys`); // mutation:fold5
  if (rec.seed !== SEED) p.push(`seed ${JSON.stringify(rec.seed)} is not the recorded seed ${JSON.stringify(SEED)}`);
  if (JSON.stringify(rec) !== JSON.stringify(foldsRecordR11(root))) p.push("the file is not what folds-r10.json and the dev3 census manifests give"); // mutation:whole
  return p;
}

// repo -> { fold, lang } from a committed folds file (round 10 or 11, by its `plan`); refuses a file that fails its checks.
export function loadFolds(path = join(repoRootDir, FOLDS_FILE_R11), root = repoRootDir) {
  const rec = JSON.parse(readFileSync(path, "utf8"));
  const r11 = rec?.plan === "eval/study/PLAN-R11.md §5";
  const problems = r11 ? foldsProblemsR11(rec, root) : foldsProblems(rec, buildSet(root));
  if (problems.length) throw new Error(`${r11 ? FOLDS_FILE_R11 : FOLDS_FILE}: ${problems.join("; ")}`);
  const repos = new Map();
  for (const f of rec.folds) for (const lang of Object.keys(rec.languages)) for (const r of f[lang]) {
    if (repos.has(r)) throw new Error(`${path}: ${r} is in two folds`);
    repos.set(r, { fold: f.fold, lang });
  }
  return { record: rec, repos, folds: rec.folds.map((f) => f.fold) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = parseArgs(process.argv.slice(2), { flags: ["check", "print", "r11"] });
  if (args.print) console.log(JSON.stringify(args.r11 ? foldsRecordR11() : foldsRecord(), null, 2));
  else if (args.check) {
    let bad = false;
    for (const [file, problems] of [[FOLDS_FILE, (r) => foldsProblems(r)], [FOLDS_FILE_R11, (r) => foldsProblemsR11(r)]]) {
      const rec = JSON.parse(readFileSync(join(repoRootDir, file), "utf8"));
      const p = problems(rec);
      if (p.length) {
        for (const x of p) console.error(`${file}: ${x}`);
        bad = true;
        continue;
      }
      for (const f of rec.folds) console.log(`${file} fold ${f.fold}: ts ${f.ts.length} (${f.ts.join(", ")}); py ${f.py.length} (${f.py.join(", ")})`);
      console.log(`${file}: ok (seed ${rec.seed}, sha256 ${rec.sha256})`);
    }
    if (bad) process.exit(1);
  } else die("usage: folds.mjs --check | --print [--r11]");
}
