//! `drift export agents-md`: keep a short, generated block of accepted
//! conventions in AGENTS.md (or CLAUDE.md) so every agent reads them up front.

use crate::project::{Project, blocks, is_suggestion};
use drift_mine::report::sanitize;

pub const START: &str = "<!-- drift:start (generated by `drift export agents-md`; edit conventions with `drift review`) -->";
pub const END: &str = "<!-- drift:end -->";
/// Rules exported: these files load on every turn, so keep them short.
pub const MAX_RULES: usize = 10;
/// When to ask Drift before searching, in the block and in the plugin's SKILL.md: only
/// "how is X done here" and structure questions; grep stays the tool for the rest.
pub const LOOKUP_RULE: &str = "Before searching for how this codebase handles auth, validation, errors, routes or data access, or for its structure (packages, entry points, a file's role), run `drift card <target file>` (or `drift practices --path <file>` when available). Grep only for what it reports as not known. Keep using grep to find where a symbol is called or a string is defined.";

/// The setup questions, for an agent: where to start and the rule it answers under.
pub const SETUP_RULE: &str = "Drift asks a few questions only someone who knows the repository can settle (is a compose file only for tests, which Terraform target group serves a service, is a helper the tenant check): `drift setup --agent-brief` says how an agent goes through them. An answer that would make Drift less cautious waits for a person (`drift setup --review`). Run drift with DRIFT_AGENT=1 set: your runs are then an agent's, on a terminal too.";

/// The open routes, for an agent: one sentence pointing to how it works through them.
pub const INVESTIGATE_RULE: &str = "Every route Drift could not settle is listed by `drift investigate`, with the code to read: `drift investigate --agent-brief` says how an agent works through them (an outcome that would make a fact waits for a person; findings stay local files).";

pub fn block(p: &Project) -> String {
    let mut accepted: Vec<_> = p.accepted().collect();
    // Rules first (the default tier, and any suggestion a person set to block), then
    // suggestions that advise; within a group blocking rules first, then strongest
    // evidence; ties by id for stable output.
    accepted.sort_by(|a, b| {
        is_suggestion(a)
            .cmp(&is_suggestion(b))
            .then(blocks(b).cmp(&blocks(a)))
            .then(b.evidence.lower_bound.total_cmp(&a.evidence.lower_bound))
            .then(a.id.cmp(&b.id))
    });
    let mut out = format!("{START}\n## Codebase conventions (learned by Drift)\n");
    if accepted.is_empty() {
        out.push_str("\nNo accepted conventions yet.\n");
    }
    // Over all accepted rules; those that block sort first.
    let blocking = accepted.iter().filter(|c| blocks(c)).count();
    let mut last = None;
    for c in accepted.iter().take(MAX_RULES) {
        let sugg = is_suggestion(c);
        if last != Some(sugg) {
            if sugg {
                out.push_str("\n### Suggestions (weaker conventions, advice only: follow them where they fit; where one does not, no action is needed)\n\n");
            } else if blocking == 0 {
                out.push_str("\n### Rules (0 block: these advise, so a new violation is reported but fails no check; where one does not fit, no action is needed)\n\n");
            } else {
                out.push_str(&format!(
                    "\n### Rules ({blocking} block: a new violation of one marked blocks fails `drift check`; the others advise, and need no action where they do not fit)\n\n"
                ));
            }
            last = Some(sugg);
        }
        out.push_str(&format!(
            "- {} ({}/{} follow it{}). Example: `{}`\n",
            sanitize(&c.summary, 240),
            c.evidence.holders,
            c.evidence.total,
            if blocks(c) { ", blocks" } else { "" },
            sanitize(&c.example, 160)
        ));
    }
    // The cut line says how many of the rules left out block (the sort above puts
    // them first, so only more than MAX_RULES blocking rules leave any out), in the
    // words of every other capped list (`drift_mine::report::cut_note`).
    if accepted.len() > MAX_RULES {
        let left = accepted.len() - MAX_RULES;
        let blocking_left = blocking.saturating_sub(MAX_RULES);
        out.push_str(&format!(
            "- …and {left} more{}: run `drift check` before finishing.\n",
            drift_mine::report::cut_note(blocking_left, left - blocking_left)
        ));
    }
    out.push_str(
        "\nN/M: members of the rule's role that follow it; a rule's known exceptions follow \"except\". Before creating a file, run `drift example <path>` to find the file to copy.",
    );
    // The way out of a rule that blocks; advice has no need of one.
    if blocking > 0 {
        out.push_str(" `// drift-ignore <id>: <reason>` is for an intentional exception to a rule that blocks; advice needs none.");
    }
    out.push_str("\n\n");
    out.push_str(SETUP_RULE);
    out.push(' ');
    out.push_str(INVESTIGATE_RULE);
    out.push_str("\n\n");
    out.push_str(LOOKUP_RULE);
    out.push('\n');
    out.push_str(END);
    out
}

/// Replace the generated block in `existing`, or append it.
pub fn splice(existing: &str, block: &str) -> String {
    match (existing.find(START), existing.find(END)) {
        (Some(s), Some(e)) if e > s => {
            format!("{}{}{}", &existing[..s], block, &existing[e + END.len()..])
        }
        _ if existing.trim().is_empty() => format!("{block}\n"),
        _ => format!("{}\n\n{block}\n", existing.trim_end()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The plugin's skill gives agents the same rule, word for word.
    #[test]
    fn the_skill_carries_the_lookup_rule() {
        let skill = std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../integrations/claude-code/skills/drift/SKILL.md"
        ))
        .unwrap();
        let flat = skill.split_whitespace().collect::<Vec<_>>().join(" ");
        assert!(flat.contains(LOOKUP_RULE), "SKILL.md lacks the rule");
        // Scoped to convention and structure questions: never "instead of grep" at large.
        assert!(!flat.contains("instead of grep") && !LOOKUP_RULE.contains("instead of grep"));
        // Every tool the skill pre-approves is a read-only one the hook approves too.
        let allowed = skill
            .lines()
            .find_map(|l| l.strip_prefix("allowed-tools: "))
            .expect("allowed-tools");
        for t in allowed.split(", ") {
            let ok = match t
                .strip_prefix("Bash(drift ")
                .and_then(|t| t.strip_suffix(":*)"))
            {
                // Not `drift practices`: its prefix would cover `practices promote`, which writes.
                Some(cmd) => cmd != "practices" && crate::lookup::READ_ONLY_COMMANDS.contains(&cmd),
                None => crate::lookup::read_only_tool(t),
            };
            assert!(ok, "{t}");
        }
    }

    #[test]
    fn splice_replaces_or_appends() {
        let b = format!("{START}\nnew\n{END}");
        assert_eq!(splice("", &b), format!("{b}\n"));
        assert_eq!(splice("# Agents\n", &b), format!("# Agents\n\n{b}\n"));
        let old = format!("# Agents\n\n{START}\nold\n{END}\n\nmore\n");
        assert_eq!(splice(&old, &b), format!("# Agents\n\n{b}\n\nmore\n"));
    }
}
