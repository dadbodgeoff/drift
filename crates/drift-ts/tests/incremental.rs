fn full(root: &Path) -> RepoFacts {
    scan(
        root,
        &ScanOptions {
            cache_dir: None,
            threads: 0,
        },
    )
    .unwrap()
    .0
}

/// Every file's incremental facts equal its entry in a fresh full scan.
fn assert_matches_full(root: &Path, cache: &Path, step: &str) {
    let full = full(root);
    let opts = ScanOptions {
        cache_dir: Some(cache.to_path_buf()),
        threads: 0,
    };
    for f in &full.files {
        let one = scan_file(root, &opts, &f.path)
            .unwrap()
            .unwrap_or_else(|| panic!("{step}: no incremental scan for {}", f.path));
        assert_eq!(one.files, std::slice::from_ref(f), "{step}: {}", f.path);
        let models: Vec<_> = full
            .models
            .iter()
            .filter(|m| m.path == f.path)
            .cloned()
            .collect();
        assert_eq!(one.models, models, "{step}: models of {}", f.path);
        assert_eq!(one.packages, full.packages, "{step}: packages");
        assert_eq!(one.lint, full.lint, "{step}: lint configs");
    }
    // Files that are not analysed have no facts.
    for rel in ["src/gen.ts", "README.md", "src/missing.ts"] {
        let one = scan_file(root, &opts, rel).unwrap().unwrap();
        assert!(one.files.is_empty(), "{step}: {rel}");
    }
}

#[test]
fn single_file_scan_matches_full_scan() {
    let repo = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let r = repo.path();
    fixture(r);
    let opts = ScanOptions {
        cache_dir: Some(cache.path().to_path_buf()),
        threads: 0,
    };
    assert!(
        scan_file(r, &opts, "src/server.ts").unwrap().is_none(),
        "no index before the first full scan"
    );
    for rel in [
        "package.json",
        "packages/ui/package.json",
        "prisma/schema.prisma",
        "api/app.py",
    ] {
        assert!(scan_file(r, &opts, rel).unwrap().is_none(), "{rel}");
    }
    let (cached, _) = scan(r, &opts).unwrap();
    assert_eq!(cached, full(r));
    assert_eq!(cached.lint.len(), 2, "{:?}", cached.lint);
    let f = |p: &str| -> drift_core::FileFacts {
        scan_file(r, &opts, p).unwrap().unwrap().files[0].clone()
    };
    let users = f("src/routes/users.ts");
    assert!(
        users.entry_points[0].route.as_deref() == Some("/api/users/:id"),
        "mount prefix applied: {:?}",
        users.entry_points
    );
    assert!(f("src/lib/util.ts").has_test);
    assert!(!f("src/components/profile.tsx").client_leaks.is_empty());
    assert_matches_full(r, cache.path(), "initial");

    // A mount of a file that does not exist yet, then the file.
    write(
        r,
        "src/routes/index.ts",
        "import express from \"express\";\nimport users from \"./users\";\nimport orders from \"./orders\";\n\nconst v1 = express.Router();\nv1.use(\"/users\", users);\nv1.use(\"/orders\", orders);\n\nexport { v1 };\n",
    );
    assert_matches_full(r, cache.path(), "mount of a missing file");
    write(
        r,
        "src/routes/orders.ts",
        "import express from \"express\";\n\nconst r = express.Router();\nr.post(\"/\", (req: any, res: any) => res.json({}));\nexport default r;\n",
    );
    assert_matches_full(r, cache.path(), "new mounted file");
    assert_eq!(
        f("src/routes/orders.ts").entry_points[0].route.as_deref(),
        Some("/api/orders")
    );

    // A re-exported module and its test disappear.
    std::fs::remove_file(r.join("src/lib/util.ts")).unwrap();
    std::fs::remove_file(r.join("src/lib/util.test.ts")).unwrap();
    assert_matches_full(r, cache.path(), "deleted re-export source");

    // Server-only code stops being server-only; a workspace package is renamed;
    // the tsconfig alias moves.
    write(r, "src/lib/db.ts", "export const db = { query() {} };\n");
    assert_matches_full(r, cache.path(), "server root removed");
    write(
        r,
        "packages/ui/package.json",
        r#"{ "name": "@acme/kit", "main": "src/index.ts" }"#,
    );
    assert_matches_full(r, cache.path(), "workspace package renamed");
    write(
        r,
        "tsconfig.json",
        r#"{ "compilerOptions": { "baseUrl": ".", "paths": { "@/*": ["./lib/*"] } } }"#,
    );
    assert_matches_full(r, cache.path(), "alias moved");
    write(
        r,
        ".oxlintrc.json",
        r#"{ "rules": { "no-console": "off" } }"#,
    );
    assert_matches_full(r, cache.path(), "lint config changed");

    // Same-size rewrites right after a scan (the stamp may not change) are seen.
    let (_, _) = scan(r, &opts).unwrap();
    write(
        r,
        "src/middleware/auth.ts",
        "export function xyzz(req: any, res: any, next: any) {\n  next();\n}\n",
    );
    assert_matches_full(r, cache.path(), "same-size rewrite");

    // A full scan through the index equals one without it.
    assert_eq!(scan(r, &opts).unwrap().0, full(r));
}

#[test]
fn single_file_scan_is_deterministic() {
    let repo = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let r = repo.path();
    fixture(r);
    let opts = |threads| ScanOptions {
        cache_dir: Some(cache.path().to_path_buf()),
        threads,
    };
    scan(r, &opts(0)).unwrap();
    for rel in [
        "src/server.ts",
        "src/routes/users.ts",
        "src/components/profile.tsx",
    ] {
        let a = serde_json::to_string(&scan_file(r, &opts(1), rel).unwrap()).unwrap();
        let b = serde_json::to_string(&scan_file(r, &opts(4), rel).unwrap()).unwrap();
        assert_eq!(a, b, "{rel}");
    }
}

#[test]
fn a_base_chain_too_long_to_follow_falls_back_to_a_full_scan() {
    let repo = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let r = repo.path();
    write(r, "package.json", r#"{ "name": "app" }"#);
    // C70 extends C69 extends ... extends C0: more base files than a single-file scan
    // links (64), so it must not check against a chain cut short.
    write(r, "src/c0.ts", "export class C0 {}\n");
    for i in 1..=70 {
        write(
            r,
            &format!("src/c{i}.ts"),
            &format!(
                "import {{ C{p} }} from \"./c{p}\";\nexport class C{i} extends C{p} {{}}\n",
                p = i - 1
            ),
        );
    }
    let opts = ScanOptions {
        cache_dir: Some(cache.path().to_path_buf()),
        threads: 0,
    };
    let (full, _) = scan(r, &opts).unwrap();
    assert!(scan_file(r, &opts, "src/c70.ts").unwrap().is_none());
    // A short chain is followed: its base files are context, not checked files.
    let one = scan_file(r, &opts, "src/c3.ts").unwrap().unwrap();
    assert_eq!(
        one.files,
        [full
            .files
            .iter()
            .find(|f| f.path == "src/c3.ts")
            .unwrap()
            .clone()]
    );
    let context: Vec<&str> = one.context_files.iter().map(|f| f.path.as_str()).collect();
    assert_eq!(context, ["src/c0.ts", "src/c1.ts", "src/c2.ts"]);
}

#[test]
fn a_wrapper_chain_is_loaded_as_context() {
    let repo = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let r = repo.path();
    write(r, "package.json", r#"{ "name": "app" }"#);
    write(
        r,
        "src/trpc.ts",
        "import { initTRPC } from \"@trpc/server\";\nconst t = initTRPC.create();\nexport const procedure = t.procedure;\n",
    );
    write(
        r,
        "src/procedures.ts",
        "import { procedure } from \"./trpc\";\nimport { isAuthed } from \"./mw\";\nexport const authedProcedure = procedure.use(isAuthed);\n",
    );
    write(
        r,
        "src/mw.ts",
        "export const isAuthed = (o: any) => o.next();\n",
    );
    write(
        r,
        "src/bookings/util.ts",
        "import { authedProcedure } from \"../procedures\";\nexport const bookingsProcedure = authedProcedure.input(s).use(async ({ next }) => next());\nexport const helper = () => 1;\n",
    );
    write(
        r,
        "src/bookings/_router.ts",
        "import { bookingsProcedure } from \"./util\";\nexport const edit = bookingsProcedure.mutation(async ({ input }) => input);\n",
    );
    let opts = ScanOptions {
        cache_dir: Some(cache.path().to_path_buf()),
        threads: 0,
    };
    let (full, _) = scan(r, &opts).unwrap();
    let one = scan_file(r, &opts, "src/bookings/_router.ts")
        .unwrap()
        .unwrap();
    assert_eq!(
        one.files,
        [full
            .files
            .iter()
            .find(|f| f.path == "src/bookings/_router.ts")
            .unwrap()
            .clone()]
    );
    // The chain `bookingsProcedure` -> `authedProcedure` -> `procedure`, with the
    // derived bindings only (not `helper`, nor the middleware's file).
    let context: Vec<(&str, Vec<(&str, &str)>)> = one
        .context_files
        .iter()
        .map(|f| {
            (
                f.path.as_str(),
                f.symbols
                    .iter()
                    .map(|s| (s.name.as_str(), s.derives_from.as_str()))
                    .collect(),
            )
        })
        .collect();
    assert_eq!(
        context,
        [
            (
                "src/bookings/util.ts",
                vec![(
                    "bookingsProcedure",
                    "src/procedures.ts#authedProcedure.input().use()"
                )]
            ),
            (
                "src/procedures.ts",
                vec![("authedProcedure", "src/trpc.ts#procedure.use()")]
            ),
            (
                "src/trpc.ts",
                vec![("procedure", "src/trpc.ts#t.procedure")]
            ),
        ]
    );
}

/// A single-file scan of a router reads the files that prove where its procedures'
/// builders come from (aliases, barrels, default exports), so each file's facts are
/// those of a full scan: the procedures a full scan proves, and no others.
#[test]
fn single_file_scan_proves_trpc_builders_as_a_full_scan_does() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/trpc-origin");
    let cache = tempfile::tempdir().unwrap();
    let opts = ScanOptions {
        cache_dir: Some(cache.path().to_path_buf()),
        threads: 0,
    };
    let (full, _) = scan(&root, &opts).unwrap();
    let proven = full
        .files
        .iter()
        .find(|f| f.path == "server/routers/proven.ts")
        .unwrap();
    assert_eq!(proven.entry_points.len(), 10);
    for f in &full.files {
        let one = scan_file(&root, &opts, &f.path).unwrap().unwrap();
        assert_eq!(one.files, std::slice::from_ref(f), "{}", f.path);
    }
}

