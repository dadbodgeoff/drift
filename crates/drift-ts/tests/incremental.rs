//! Single-file (incremental) scans must give exactly the facts a full scan gives
//! for that file, whatever changed since the scan index was written.

use std::path::Path;

use drift_core::RepoFacts;
use drift_ts::{ScanOptions, scan, scan_file};

fn write(root: &Path, rel: &str, body: &str) {
    let p = root.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, body).unwrap();
}

